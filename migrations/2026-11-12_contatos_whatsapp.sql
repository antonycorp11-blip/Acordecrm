-- Aplicar manualmente no Supabase antes de usar a importação.
create table if not exists public.contatos_whatsapp (
  id bigint generated by default as identity primary key,
  telefone text not null unique,
  primeira_conversa date not null,
  ultima_conversa date,
  mes text not null,
  status text not null default 'pendente' check (status in ('pendente', 'nao_respondeu', 'respondeu', 'interessado', 'nao_quer', 'numero_invalido')),
  tentativas smallint not null default 0 check (tentativas between 0 and 2),
  ultimo_contato_em timestamptz,
  atribuido_em date,
  lead_id bigint,
  criado_em timestamptz not null default now()
);

create index if not exists contatos_whatsapp_fila_idx
  on public.contatos_whatsapp (primeira_conversa, id);
create index if not exists contatos_whatsapp_atribuido_idx
  on public.contatos_whatsapp (atribuido_em);
